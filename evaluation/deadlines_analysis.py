"""
deadlines_analysis.py — why does BM25 miss the deadline questions?

Builds the same index as evaluate.py (university_knowledge.txt, 400-word chunks,
80-word overlap), then for each answerable "deadlines" question and each retrieval
mode reports:
  * which chunk(s) contain the gold passage, and their BM25 score and rank
  * the top-3 chunks BM25 actually returns, with scores and per-term contributions
It also checks found_urls.txt for the crawl coverage of deadline-related pages.

The scores are recomputed with the same formula as rag._bm25_search, and the
script checks that its top-3 is identical to rag._bm25_search's in every case.
No API calls; the translate mode uses the reference translation in questions.json.

    python evaluation/deadlines_analysis.py   ->  evaluation/deadlines_analysis.md
"""

import json
import math
import os
import sys
from collections import Counter

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, ROOT)
sys.path.insert(0, HERE)

import rag  # noqa: E402
from evaluate import normalize  # noqa: E402

K1, B, TOP_K = 1.5, 0.75, 3
MODES = ("baseline", "stopwords", "translate")


def doc_tokens(doc, mode):
    return doc["tokens"] if mode == "baseline" else rag._content_tokens(doc)


def query_tokens(query, mode):
    toks = rag._tokenize(query)
    return toks if mode == "baseline" else [t for t in toks if t not in rag.STOPWORDS]


def score_all(query, mode, chunks):
    """BM25 exactly as rag._bm25_search, but keeping every score and per-term contributions."""
    qtoks = query_tokens(query, mode)
    n = len(chunks)
    avgdl = sum(len(doc_tokens(d, mode)) for d in chunks) / n
    idf = {}
    for t in set(qtoks):
        df = sum(1 for d in chunks if t in doc_tokens(d, mode))
        idf[t] = (math.log((n - df + 0.5) / (df + 0.5) + 1), df)
    results = []
    for i, d in enumerate(chunks):
        toks = doc_tokens(d, mode)
        dl, tf = len(toks), Counter(toks)
        contrib = Counter()
        for t in qtoks:  # repeated query terms count once per occurrence, as in rag.py
            if tf[t] > 0:
                contrib[t] += idf[t][0] * tf[t] * (K1 + 1) / (tf[t] + K1 * (1 - B + B * dl / avgdl))
        results.append((sum(contrib.values()), i, contrib))
    ranked = sorted([r for r in results if r[0] > 0], key=lambda r: (r[0], r[1]), reverse=True)
    return qtoks, idf, results, ranked


def chunk_sources(chunk_index, words, source_starts):
    """Source page(s) a chunk covers: the page it starts in plus any page starting inside it."""
    start, end = chunk_index * 320, chunk_index * 320 + 400
    before = [u for pos, u in source_starts if pos <= start]
    inside = [u for pos, u in source_starts if start < pos < end]
    return ([before[-1]] if before else []) + inside


def short(url):
    return url.replace("https://www.uniduna.hu", "")


def contrib_str(contrib):
    return ", ".join(f"`{t}` {v:.2f}" for t, v in contrib.most_common())


def main():
    with open(os.path.join(ROOT, "university_knowledge.txt"), encoding="utf-8") as f:
        kb = f.read()
    rag.SUPABASE_AVAILABLE = False
    rag.add_document(kb, source="university_knowledge.txt", office="general")
    chunks = list(rag._doc_chunks)
    words = kb.split()
    # page markers are "SOURCE: <url>" for HTML pages and "SOURCE (PDF): <url>" for PDFs
    source_starts = []
    for i, w in enumerate(words[:-2]):
        if w == "SOURCE:":
            source_starts.append((i + 1, words[i + 1]))
        elif w == "SOURCE" and words[i + 1] == "(PDF):":
            source_starts.append((i + 2, "PDF: " + words[i + 2]))

    with open(os.path.join(HERE, "questions.json"), encoding="utf-8") as f:
        questions = [q for q in json.load(f) if q["category"] == "deadlines" and q["answerable"]]

    out = ["# Deadlines category — retrieval analysis", "",
           f"Index: `university_knowledge.txt`, {len(chunks)} chunks of 400 words with 80-word overlap "
           f"(rag.py defaults). BM25 k1={K1}, b={B}, top-{TOP_K}. Generated by "
           "`evaluation/deadlines_analysis.py` (no API calls; translate mode uses the reference "
           "translation from questions.json, the real run used the LLM's translation — see the "
           "`search_query` column of that run's CSV).", ""]
    summary_rows = []

    for q in questions:
        gold = normalize(q["source_passage"])
        gold_chunks = [i for i, d in enumerate(chunks) if gold in normalize(d["text"])]
        in_kb = gold in normalize(kb)
        out += [f"## {q['id']} ({q['language']}): {q['question']}", "",
                f"- Gold passage: “{q['source_passage']}”",
                f"- Source page: `{short(q['source_url'])}`",
                f"- Passage in knowledge base: **{'yes' if in_kb else 'NO'}**; contained in chunk(s) "
                f"{', '.join(f'#{i}' for i in gold_chunks) or 'none'}", ""]
        for mode in MODES:
            query = q["question"]
            if mode == "translate" and rag.is_hungarian(query):
                query = q.get("question_en") or query
            qtoks, idf, results, ranked = score_all(query, mode, chunks)

            expected = rag._bm25_search(query, office=None, k=TOP_K, mode=mode)
            mine = [chunks[i] for _, i, _ in ranked[:TOP_K]]
            assert [id(d) for d in mine] == [id(d) for d in expected], f"score mismatch {q['id']} {mode}"

            rank_of = {i: r + 1 for r, (_, i, _) in enumerate(ranked)}
            gold_info = []
            for gi in gold_chunks:
                s, _, c = results[gi]
                gold_info.append((rank_of.get(gi), s, gi, c))
            best = min(gold_info, key=lambda g: g[0] or 10 ** 9) if gold_info else None
            summary_rows.append((q["id"], mode, best[0] if best else None,
                                 best[1] if best else None, ranked[TOP_K - 1][0] if len(ranked) >= TOP_K else 0))

            out += [f"### {mode}" + (f" — searched as “{query}”" if query != q["question"] else ""), "",
                    "Query terms (document frequency / IDF): "
                    + ", ".join(f"`{t}` {idf[t][1]}/{idf[t][0]:.2f}" for t in dict.fromkeys(qtoks)), ""]
            out += ["| Rank | Chunk | Score | Source page(s) | Term contributions |", "|---|---|---|---|---|"]
            for r, (s, i, c) in enumerate(ranked[:TOP_K], 1):
                out.append(f"| {r} | #{i} | {s:.2f} | {'<br>'.join(short(u) for u in chunk_sources(i, words, source_starts))} "
                           f"| {contrib_str(c)} |")
            for rank, s, gi, c in gold_info:
                out.append(f"| **{rank or '—'}** (gold) | #{gi} | {s:.2f} | "
                           f"{'<br>'.join(short(u) for u in chunk_sources(gi, words, source_starts))} | "
                           f"{contrib_str(c) or 'no query term matches'} |")
            out.append("")

    out += ["## Summary", "", "| Question | Mode | Gold chunk rank | Gold score | 3rd-place score |",
            "|---|---|---|---|---|"]
    for qid, mode, rank, s, third in summary_rows:
        out.append(f"| {qid} | {mode} | {rank or 'not matched'} | {'' if s is None else f'{s:.2f}'} | {third:.2f} |")

    path = os.path.join(HERE, "deadlines_analysis_data.md")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print("\n".join(out))
    print(f"\nWritten to {path}")


if __name__ == "__main__":
    main()
